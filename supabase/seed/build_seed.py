#!/usr/bin/env python3
"""Builds supabase/seed.sql: the topic list and every question in data/ (the original bank plus new packs).
Safe to run again: questions are matched on their normalised text, so nothing is duplicated."""
import json, os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, 'data')
# id, name, icon, colour, category, position — same as the web game
TOPICS = [
 ('gk','General Knowledge','bulb','#ffc53d','know'), ('brain','Brain Teasers','puzzle','#c084fc','know'),
 ('history','History','hourglass','#e9a85a','know'), ('science','Science','flask','#3ddc84','know'),
 ('space','Space','rocket','#7b86ff','know'), ('animals','Animals','paw','#5fd38d','know'),
 ('tech','Tech & Internet','cpu','#3fc8e8','know'), ('bollywood','Bollywood','clapper','#ff4fa3','pop'),
 ('hollywood','Hollywood','film','#ff6b5a','pop'), ('music','Music','music','#c77dff','pop'),
 ('love','Love & Romance','heart','#ff7096','pop'), ('geography','Geography','globe','#38d6ff','world'),
 ('capitals','Capitals & Flags','flag','#5aa9ff','world'), ('india','India','landmark','#ff9933','world'),
 ('food','Food & Drink','utensils','#ff8a65','world'), ('cricket','Cricket','cricket','#a3e635','play'),
 ('sports','Sports','trophy','#2ec4b6','play'), ('gaming','Video Games','gamepad','#a78bfa','play'),
 ('emoji','Emoji Guess','smile','#ffd84d','pop'), ('flags','Flags','flagw','#ff6b6b','world'),
 ('mythology','Mythology','trident','#f4a259','know'), ('books','Books','book','#4fc3b4','know'),
 ('tv','TV Shows','tv','#f472b6','pop'), ('art','Art & Culture','palette','#fb923c','know'),
]
def q(s): return "'" + str(s).replace("'", "''") + "'"
# keeps letters, digits and emoji; drops spaces and ASCII punctuation (must match game.norm in SQL)
def norm(s): return re.sub(r'[\s!-/:-@\[-`{-~]+', '', s.lower())
out = ['-- generated by supabase/seed/build_seed.py — do not edit by hand', 'begin;']
out.append('insert into public.topics (id, name, icon, color, category, position) values')
out.append(',\n'.join(f'({q(t[0])},{q(t[1])},{q(t[2])},{q(t[3])},{q(t[4])},{i})' for i, t in enumerate(TOPICS)))
out.append('on conflict (id) do update set name = excluded.name, icon = excluded.icon, color = excluded.color, category = excluded.category, position = excluded.position;')
ids = {t[0] for t in TOPICS}; rows = []; seen = set(); per = {}
for path in sorted(glob.glob(os.path.join(DATA, '*.json'))):
    name = os.path.basename(path)[:-5]
    topic = re.sub(r'_\d+$', '', name)
    if topic not in ids: continue
    src = 'claude' if re.search(r'_\d+$', name) and int(name.rsplit('_', 1)[1]) >= 3 else 'bank'
    for r in json.load(open(path, encoding='utf-8')):
        n = norm(r['q'])
        if n in seen or len(r['w']) != 3 or len({r['a'].strip().lower(), *[w.strip().lower() for w in r['w']]}) != 4: continue
        seen.add(n); per[topic] = per.get(topic, 0) + 1
        rows.append(f"({q(topic)},{q(r['q'])},{q(r['a'])},array[{','.join(q(w) for w in r['w'])}],{int(r.get('d', 2))},{q(src)},{q('original')},{q(n)})")
for i in range(0, len(rows), 500):
    out.append('insert into public.questions (topic_id, q, a, w, difficulty, source, license, norm) values')
    out.append(',\n'.join(rows[i:i + 500]))
    out.append('on conflict (norm) do nothing;')
out.append('commit;')
open(os.path.join(ROOT, 'supabase', 'seed.sql'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(rows), 'questions', dict(sorted(per.items())))
